"""Make .ste-lint.toml from the STE register in a glossary.

Usage: python3 allowlist.py GLOSSARY [OUT]
  GLOSSARY  a markdown file with a "## Part 2" that has the sections
            Technical Names, Norwegian words, Domain words, Technical Verbs
  OUT       the file to write, default .ste-lint.toml in the current directory

The rules of ste-lint examine one token at a time, and the tagger sometimes
reads a noun as a verb. Thus the allowlist has each word with no part of
speech, each token of a multi-word name, the plural form, and the usual
verb forms.

"""

import json
import re
import sys
from pathlib import Path

STOP = {"and", "of", "the", "a", "an", "in", "for", "to", "or"}


def section(text: str, heading: str) -> list[str]:
    start = text.index(heading)
    end = text.find("\n### ", start + 1)
    body = text[start:] if end < 0 else text[start:end]
    return [m.group(1).lower() for m in re.finditer(r"^- `([^`]+)`", body, re.M)]


def verb_forms(verb: str):
    yield verb
    yield verb + "s"
    yield verb + "es"
    yield verb + "d" if verb.endswith("e") else verb + "ed"
    if verb.endswith("y"):
        yield verb[:-1] + "ied"
        yield verb[:-1] + "ies"


def main() -> None:
    if len(sys.argv) not in (2, 3):
        print(__doc__)
        raise SystemExit(2)
    glossary = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) == 3 else Path(".ste-lint.toml")
    text = glossary.read_text()
    part1 = text.split("## Part 1")[1].split("## Part 2")[0]
    nouns = set()
    for heading in ("### Technical Names", "### Norwegian words", "### Domain words"):
        nouns.update(section(text, heading))
    nouns.update(m.lower() for m in re.findall(r"^\| \*\*([^*]+)\*\*", part1, re.M))
    verbs = set(section(text, "### Technical Verbs"))

    allowed = set()
    for noun in nouns:
        allowed.add(noun)
        allowed.update(t for t in re.split(r"[ -]", noun) if t not in STOP and len(t) > 1)
    allowed |= {w + "s" for w in list(allowed) if " " not in w}
    verb_set = {form for verb in verbs for form in verb_forms(verb)}

    def toml_list(words):
        return ", ".join(json.dumps(w, ensure_ascii=False) for w in sorted(words))

    out.write_text(
        f"# Generated by ste-lint/scripts/allowlist.py from {glossary}.\n"
        "# Do not edit. Git ignores this file.\n"
        f"technical_nouns = [{toml_list(allowed)}]\n"
        f"technical_verbs = [{toml_list(verb_set)}]\n"
    )
    print(f"{out}: {len(allowed)} nouns, {len(verb_set)} verbs")


if __name__ == "__main__":
    main()
